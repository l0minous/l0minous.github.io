"""Create committed WebP display images; originals remain untouched.
Run with Pillow installed: python3 scripts/optimize-gallery.py
"""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from pathlib import Path
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src/components/creative-work'
ITEMS = json.loads((DATA / 'gallery-originals.json').read_text())
TITLES = {1: 'Gathering in the park', 2: 'Sunset over the trees', 3: 'An outdoor gathering', 4: 'Evening in the park', 5: 'The park path', 6: 'Friends in the park', 7: 'Sunlight through the trees', 8: 'Sunlit trees', 9: 'A picnic in the park', 10: 'Under the bridge', 11: 'Waterfront at sunset', 12: 'Floodlit field', 13: 'Trees along the path', 14: 'In the forest', 15: 'Oath Gaming — first place', 16: 'Oath Gaming — going live', 17: 'Oath Gaming — game day', 18: 'Going live', 19: 'MVP', 33: 'Something worth fighting for', 34: 'City through a window'}


def title_for(item):
    if item['id'] in TITLES:
        return TITLES[item['id']]
    if item['original'].startswith('/creative-work/'):
        return Path(item['original']).stem.replace('-', ' ').replace('_', ' ').capitalize()
    words = item['label'].title()
    for old, new in [('Yfp', 'YFP'), ('Nrg', 'NRG'), ('Pgc', 'PGC')]:
        words = words.replace(old, new)
    return words


def optimize(item):
    source = ROOT / 'public' / item['original'].lstrip('/')
    stamp = sha256(source.read_bytes() + str(item['rotation']).encode() + b'gallery-v1').hexdigest()[:10]
    paths = {}
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened)
        image.load()
        if image.mode not in ('RGB', 'RGBA'):
            image = image.convert('RGB')
        if item['rotation']:
            image = image.rotate(-item['rotation'], expand=True)
        width, height = image.size
        profile = image.info.get('icc_profile')
        for variant, maximum, quality in [('thumbs', 640, 76), ('previews', 1800, 84)]:
            path = ROOT / 'public' / 'gallery' / variant / f"{item['id']:02d}-{stamp}.webp"
            path.parent.mkdir(parents=True, exist_ok=True)
            resized = image.copy()
            resized.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
            options = {'quality': quality, 'method': 6}
            if profile:
                options['icc_profile'] = profile
            resized.save(path, 'WEBP', **options)
            resized.close()
            paths[variant] = '/' + path.relative_to(ROOT / 'public').as_posix()
    return {
        'id': item['id'],
        'title': title_for(item),
        'detail': 'Photography' if item['id'] <= 14 else ('Graphic design' if item['id'] <= 19 or item['id'] == 33 else item['label'].capitalize()),
        'thumbnail': paths['thumbs'],
        'preview': paths['previews'],
        'original': item['original'],
        'width': width, 'height': height,
        'link': 'https://www.behance.net/dilerzaza' if item['id'] <= 14 else item['link'],
    }


with ThreadPoolExecutor(max_workers=4) as executor:
    images = list(executor.map(optimize, ITEMS))
assert len(images) == len(ITEMS) == 43
interface = '''// Generated by scripts/optimize-gallery.py. Original images are preserved.
export interface GalleryImage {
  id: number;
  title: string;
  detail: string;
  thumbnail: string;
  preview: string;
  original: string;
  width: number;
  height: number;
  link: string;
}

export const galleryImages: GalleryImage[] = '''
(DATA / 'gallery-images.ts').write_text(interface + json.dumps(images, indent=2) + ';\n')
original_bytes = sum((ROOT / 'public' / item['original'].lstrip('/')).stat().st_size for item in ITEMS)
thumb_bytes = sum((ROOT / 'public' / item['thumbnail'].lstrip('/')).stat().st_size for item in images)
preview_bytes = sum((ROOT / 'public' / item['preview'].lstrip('/')).stat().st_size for item in images)
print(json.dumps({'images': len(images), 'originalMiB': round(original_bytes / 1024**2, 2), 'galleryMiB': round(thumb_bytes / 1024**2, 2), 'previewMiB': round(preview_bytes / 1024**2, 2), 'reductionPercent': round(100 * (1 - thumb_bytes / original_bytes), 1)}))
